#!/usr/bin/env python3
"""Exact product Java SSLEngine -> CPython SSLObject isolated pairing on localhost.

Only ephemeral TEST fixtures; no Android provider/Keystore, real device or deployment claim.
Java is launched only with the explicit --java/--classpath arguments, serially, <=384MiB.
Python owns the actual original native candidate/grant store in this transport interop test.
"""
import argparse
import asyncio
import json
import sqlite3
import threading
from pathlib import Path
import sys
import tempfile
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "companion"))
import device_identity as identity
import device_pairing as pairing
import device_protocol as protocol
import device_transport as transport
import device_transport_pairing as bootstrap
import test_device_pairing as fixtures


async def run(java, classpath, capture):
    from cryptography import x509
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.serialization import pkcs12
    fixture = fixtures.DevicePairingTests(); fixture.setUp()
    a_path = Path(fixture.scratch.name) / "original-native-a-review.db"
    a_db = sqlite3.connect(a_path); a_store = pairing.DeviceTrust(a_db, threading.RLock()); a_store.create_schema()
    owner_a = pairing.PairingCoordinator(a_store, fixture.a.device_id, fixture.a.instance_id)
    listeners, cases, candidates = [], [], []
    try:
        with tempfile.TemporaryDirectory(prefix="pw-only-pairing-interop-") as scratch:
            root = Path(scratch)
            invitation = fixture.coordinator.create_invitation(fixture.b, fixture.a.certificate_fingerprint, fixture.now, 10000)
            target, _ = fixtures.onboarding_target(fixture.b)
            offer = owner_a.prepare_candidate_offer(fixture.a, invitation, target, True, fixture.now, reviewed_owner_grant=fixture.reciprocal_grant())
            for name, local in (("a", fixture.a), ("wrong", fixture.b)):
                # Only keys generated by this private TEST fixture, never a user credential.
                key = serialization.load_pem_private_key(local._key(), password=None)
                (root / (name + ".p12")).write_bytes(pkcs12.serialize_key_and_certificates(name.encode(), key,
                    x509.load_der_x509_certificate(local.certificate_der), None, serialization.BestAvailableEncryption(b"localhost-test-only")))
            (root / "target.der").write_bytes(fixture.b.certificate_der)
            (root / "wrong-target.der").write_bytes(fixture.a.certificate_der)
            (root / "candidate.json").write_bytes(offer.wire_bytes())
            (root / "finalize.json").write_bytes(protocol.canonical_bytes(pairing.candidate_finalize_request(offer)))

            async def process(case, mode, port, target="target.der", key="a.p12", expires=None):
                command = [java, "-Xmx384m", "-cp", classpath, "dev.pocketengine.features.devices.transport.PairingTlsInteropProcess",
                    mode, "127.0.0.1", str(port), str(root / key), str(root / target), str(root / ("candidate.json" if mode == "candidate" else "recover.json" if mode == "recovery" else "finalize.json")), str(expires or invitation["expiresAt"])]
                child = await asyncio.create_subprocess_exec(*command, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
                try: stdout, stderr = await asyncio.wait_for(child.communicate(), 20)
                except BaseException:
                    if child.returncode is None: child.kill()
                    await child.wait(); raise
                if capture:
                    capture.mkdir(parents=True, exist_ok=True)
                    (capture / (case + ".stdout")).write_bytes(stdout); (capture / (case + ".stderr")).write_bytes(stderr)
                return child.returncode, stdout

            def inspect(raw):
                candidate = fixture.coordinator.inspect_candidate(fixture.b, raw, time.time_ns() // 1_000_000)
                candidates.append(candidate)
                return protocol.canonical_bytes(fixture.coordinator.candidate_receipt(candidate, time.time_ns() // 1_000_000))
            listener = await bootstrap.listen_candidate_lan("127.0.0.1", 0, context=bootstrap.candidate_server_context(fixture.b), owner_enabled=True,
                invitation_expires_at_ms=invitation["expiresAt"], candidate_handler=inspect)
            listeners.append(listener); port = listener.sockets[0].getsockname()[1]
            code, raw = await process("wrong-target", "candidate", port, target="wrong-target.der")
            if code == 0 or candidates: raise AssertionError("Wrong target pin reached native candidate factory")
            cases.append({"case": "wrong_target_before_offer", "javaExit": code, "nativeCandidateCalls": 0})
            code, raw = await process("candidate", "candidate", port)
            if code != 0 or len(candidates) != 1 or fixture.trust.peer(fixture.a.device_id) is not None:
                raise AssertionError("Isolated Java candidate did not remain unpaired")
            result = json.loads(raw); result["case"] = "server_auth_candidate_no_grant"; result["javaExit"] = code; cases.append(result)
            pending = fixture.coordinator.confirm_candidate_locally(fixture.b, candidates[0], True, time.time_ns() // 1_000_000, reviewed_owner_grant=fixture.grant())
            completed = []
            def complete(peer, raw):
                completed.append(peer.device_id)
                return protocol.canonical_bytes(fixture.coordinator.finalize_candidate_pairing(pending, peer, raw, fixture.grant(), time.time_ns() // 1_000_000))
            listener = await bootstrap.listen_completion_lan("127.0.0.1", 0,
                context=transport.native_device_context(fixture.b, [pending.peer_certificate_der], server_side=True), native_pending=pending, completion_handler=complete)
            listeners.append(listener); port = listener.sockets[0].getsockname()[1]
            code, _ = await process("wrong-completion-client", "completion", port, key="wrong.p12")
            if code == 0 or completed or fixture.trust.peer(fixture.a.device_id) is not None:
                raise AssertionError("Unconfirmed mTLS client reached native finalize")
            cases.append({"case": "wrong_completion_client", "javaExit": code, "nativeFinalizeCalls": 0})
            code, raw = await process("completion", "completion", port)
            if code != 0 or completed != [fixture.a.device_id] or fixture.trust.peer(fixture.a.device_id) is None:
                raise AssertionError("Confirmed Java mTLS completion did not commit original Python trust")
            result = json.loads(raw); result["case"] = "reviewed_scope_then_exact_mtls_completion"; result["javaExit"] = code; result["originalPythonGrantRows"] = fixture.db.execute("SELECT COUNT(*) FROM device_grants").fetchone()[0]; cases.append(result)
            if invitation["token"] in "\n".join(fixture.db.iterdump()): raise AssertionError("Candidate token persisted")
            frozen = protocol.canonical_bytes(fixture.trust.committed_completion(invitation["inviteId"]))
            for listener in listeners: await listener.close()
            listeners.clear()
            a_db.close(); a_db = sqlite3.connect(a_path); a_store = pairing.DeviceTrust(a_db, threading.RLock())
            owner_a = pairing.PairingCoordinator(a_store, fixture.a.device_id, fixture.a.instance_id)
            b_path = Path(fixture.scratch.name) / "original-native-b-reopened.db"
            with sqlite3.connect(b_path) as saved: fixture.db.backup(saved)
            fixture.db.close(); fixture.db = sqlite3.connect(b_path); fixture.trust = pairing.DeviceTrust(fixture.db, threading.RLock())
            fixture.a = identity.load_existing_identity(fixture.a.directory); fixture.b = identity.load_existing_identity(fixture.b.directory)
            fixture.coordinator = pairing.PairingCoordinator(fixture.trust, fixture.b.device_id, fixture.b.instance_id)
            await asyncio.sleep(max(0, (invitation["expiresAt"] - time.time_ns() // 1000000) / 1000) + 0.02)
            now = time.time_ns() // 1000000
            restored = owner_a.restore_pairing_offer(fixture.a, invitation["inviteId"], now)
            recovery = fixture.coordinator.committed_pairing_recovery(fixture.b, restored.invite_id, restored.candidate_digest, now)
            (root / "recover.json").write_bytes(protocol.canonical_bytes(pairing.candidate_recovery_request(restored)))
            recovered = []
            def recover(peer, request):
                actual = protocol.canonical_bytes(fixture.coordinator.recover_candidate_pairing(recovery, peer, request, time.time_ns() // 1000000))
                if actual != frozen: raise AssertionError("Recovery returned a new pairing transaction")
                recovered.append(peer.device_id); return actual
            reserved = await bootstrap.reserve_completion_recovery_lan("127.0.0.1", native_recovery=recovery); listeners.append(reserved)
            endpoint = reserved.address
            listener = await bootstrap.listen_completion_recovery_lan(context=transport.native_device_context(fixture.b, [recovery.peer_certificate_der], server_side=True),
                native_recovery=recovery, completion_handler=recover, reservation=reserved); listeners.append(listener)
            code, raw = await process("recovery", "recovery", endpoint[1], expires=recovery.expires_at)
            if code != 0 or recovered != [fixture.a.device_id]: raise AssertionError("Actual Java read-only recovery failed after original invitation expiry and SQL reopen")
            result = json.loads(raw); result.update(case="expired_invitation_native_recovery_same_committed_sql", javaExit=code,
                originalPythonGrantRows=fixture.db.execute("SELECT COUNT(*) FROM device_grants").fetchone()[0], sameImmutableCompletion=True, bothOriginalSqlReopened=True)
            cases.append(result)
    finally:
        for listener in listeners: await listener.close()
        a_db.close(); fixture.tearDown()
    return {"status": "PASS", "scope": "SunJSSE-or-actual-JDK-provider / CPython SSLObject, localhost TEST fixtures", "androidProviderVerified": False,
        "javaNativeGrantStoreTested": False, "temporaryFixtureCredentialsRemoved": True, "cases": cases}


def main():
    parser = argparse.ArgumentParser(); parser.add_argument("--java", required=True); parser.add_argument("--classpath", required=True); parser.add_argument("--capture-dir", type=Path)
    args = parser.parse_args(); print(json.dumps(asyncio.run(run(args.java, args.classpath, args.capture_dir)), ensure_ascii=False, indent=2))


if __name__ == "__main__": main()
