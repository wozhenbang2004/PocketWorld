/** Real production Team/BoardUI controls against a synthetic protocol host. No runtime certification. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('..', import.meta.url));
const output = process.env.TEAM_HARNESS_EVIDENCE || path.resolve(root, '../build-artifacts/host-tests/team-harness-ui');
await fs.mkdir(output, { recursive: true });
let server, browser, activePage;
const results = [];
try {
  server = await createServer({ root, server: { host: '127.0.0.1', port: 0 } }); await server.listen();
  browser = await chromium.launch({ headless: true });
  for (const viewport of [{ name: 'phone', width: 390, height: 844 }, { name: 'desktop', width: 1280, height: 900 }]) {
    const page = await browser.newPage({ viewport: { width: viewport.width, height: viewport.height } });
    activePage = page; page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(new URL('tests/team-harness-fixture.html', server.resolvedUrls.local[0]).href);
    await page.getByRole('tab', { name: '团队配置', exact: true }).click();
    await page.getByRole('button', { name: '新建团队', exact: true }).click();
    const editor = page.getByRole('dialog', { name: '新建团队', exact: true });
    const fieldButton = (scope, label) => scope.locator('.pw-selection-field').filter({ has: page.locator('.pw-field-label').filter({ hasText: new RegExp(`^${label}$`) }) }).getByRole('button');
    await editor.getByRole('textbox', { name: '团队名称', exact: true }).fill('资料协作');
    const members = editor.locator('section.pw-source-record'), member = members.nth(0);
    await member.getByRole('textbox', { name: '职责', exact: true }).fill('读取资料并核对来源');
    await members.nth(1).getByRole('textbox', { name: '职责', exact: true }).fill('复核证据并整理结论');
    await member.getByRole('button', { name: /成员做什么/ }).click();
    await page.getByRole('option', { name: '在电脑上使用执行器工作', exact: true }).click();
    await member.getByRole('button', { name: /在哪台电脑上工作/ }).click();
    await page.getByRole('option', { name: '工作电脑', exact: true }).click();
    await member.getByRole('button', { name: /工作环境与目录/ }).click();
    await page.getByRole('option', { name: '资料项目', exact: true }).click();
    await fieldButton(member, '执行器').click();
    await expect(page.getByRole('option', { name: '协作执行器', exact: true })).toBeVisible();
    await page.getByRole('option', { name: '资料执行器', exact: true }).click();
    await member.getByRole('button', { name: '核对这名成员的执行器', exact: true }).click();
    await expect(member.getByText('未找到配置的执行器，请在工作电脑核对安装位置。', { exact: true })).toBeVisible();
    await expect(editor.getByRole('button', { name: '核对本次配置', exact: true })).toBeDisabled();
    await page.screenshot({ path: path.join(output, `${viewport.name}-missing-install.png`), fullPage: true, animations: 'disabled' });
    await page.evaluate(() => window.teamHarnessFixture.available(true));
    await member.getByRole('button', { name: '核对这名成员的执行器', exact: true }).click();
    await expect(member.getByText('执行器协议已核对，尚未发送工作任务。', { exact: true })).toBeVisible();
    await expect(editor.getByRole('button', { name: '核对本次配置', exact: true })).toBeDisabled();
    await page.screenshot({ path: path.join(output, `${viewport.name}-permission-choice.png`), fullPage: true, animations: 'disabled' });
    await member.getByRole('button', { name: /模型与执行模式/ }).click();
    await fieldButton(member, '执行器使用的模型').click();
    await page.getByRole('option', { name: '分析模型', exact: true }).click();
    await fieldButton(member, '执行模式').click();
    await page.getByRole('option', { name: '常规模式', exact: true }).click();
    await member.getByText('我了解此成员使用电脑端已配置的工具权限；工作目录不是隔离沙箱，内部模型费用不能硬限', { exact: true }).click();
    await expect(member.getByRole('checkbox', { name: /我了解此成员/ })).toBeChecked();
    await expect(editor.getByRole('button', { name: '核对本次配置', exact: true })).toBeDisabled();
    await member.getByRole('button', { name: '核对这名成员的执行器', exact: true }).click();
    await expect(editor.getByRole('button', { name: '核对本次配置', exact: true })).toBeEnabled();
    await page.evaluate(() => window.teamHarnessFixture.changeConfiguration());
    await member.getByRole('button', { name: '刷新这台电脑的环境', exact: true }).click();
    await expect(editor.getByRole('button', { name: '核对本次配置', exact: true })).toBeDisabled();
    await member.getByRole('button', { name: '核对这名成员的执行器', exact: true }).click();
    await expect(editor.getByRole('button', { name: '核对本次配置', exact: true })).toBeEnabled();
    await member.getByRole('button', { name: '这次核对了哪些能力', exact: true }).click();
    await expect(member.getByText('当前不支持', { exact: true })).toHaveCount(2);
    await member.getByText('团队消息', { exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, `${viewport.name}-verified-capabilities.png`), fullPage: true, animations: 'disabled' });
    await editor.getByRole('button', { name: '核对本次配置', exact: true }).click();
    const review = page.getByRole('dialog', { name: '保存团队配置', exact: true });
    await review.getByText('已核对这次操作与原目标', { exact: true }).click();
    await expect(review.getByRole('checkbox', { name: '已核对这次操作与原目标', exact: true })).toBeChecked();
    await review.getByRole('button', { name: '确认这一次操作', exact: true }).click();
    await page.getByRole('button', { name: /资料协作/ }).click();
    await expect(page.getByText(/电脑：工作电脑/)).toBeVisible();
    await page.getByRole('button', { name: '编辑下次工作的团队', exact: true }).click();
    const edited = page.getByRole('dialog', { name: '编辑下次工作的团队', exact: true });
    await expect(fieldButton(edited, '执行器')).toContainText('资料执行器');
    await edited.getByRole('button', { name: /模型与执行模式/ }).click();
    await expect(edited.getByRole('textbox', { name: '执行器使用的模型 ID（可留空）', exact: true })).toHaveValue('analysis-v2');
    const snapshot = await page.evaluate(() => window.teamHarnessFixture.snapshot());
    const saved = snapshot.team.members[0];
    assert.equal(saved.runner, 'acp_fixture_agent'); assert.equal(saved.model, 'analysis-v2'); assert.equal(saved.modeId, 'default');
    assert.equal(saved.externalExecutionRiskAcknowledged, true); assert.equal(saved.harnessSelection, undefined);
    assert.deepEqual(saved.device, { profileId: 'fixture-computer', environmentId: 'fixture-workspace' });
    assert.ok(snapshot.calls.some(call => call.action === 'remote.probeWorker' && call.args.model === 'analysis-v2' && call.args.modeId === 'default'));
    assert.deepEqual(errors, []);
    results.push({ viewport, checks: ['actual worker directory', 'missing install', 'permission choice', 'reported model/mode', 'changed config requires fresh probe', 'unsupported capabilities', 'save/edit binding without runtime token'], pageErrors: errors });
    await page.close();
  }
  await fs.writeFile(path.join(output, 'evidence.json'), JSON.stringify({ scope: 'Production React components with synthetic host only; not a real harness or Android pass.', results }, null, 2));
  console.log(JSON.stringify({ passed: results.length, output }));
} catch (error) {
  await activePage?.screenshot({ path: path.join(output, 'failure.png'), fullPage: true });
  await fs.writeFile(path.join(output, 'failure.json'), JSON.stringify({ error: String(error), completed: results, body: await activePage?.locator('body').innerText() }, null, 2));
  throw error;
} finally { await browser?.close(); await server?.close(); }
