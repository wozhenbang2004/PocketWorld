// Keep SVG as the root: BoardUI buttons and product rows size it directly.
// Defaults affect only the optical glyph; the original controls own hit areas.
function productIcon(Source: Icon, role: 'linear' | 'bold' | 'duotone', secondaryOpacity?: number): Icon {
  return forwardRef<SVGSVGElement, Omit<IconProps, 'ref'>>(function ProductIcon(
    { size, className, style, ...props }, ref,
  ) {
    const labelled = props.alt || props['aria-label'] || props['aria-labelledby'];
    return <Source
      {...props}
      ref={ref}
      size={size}
      className={['pw-icon', 'pw-icon--' + role, className].filter(Boolean).join(' ')}
      style={size === undefined ? { fontSize: 20, ...style } : style}
      secondaryOpacity={props.secondaryOpacity ?? secondaryOpacity}
      aria-label={props['aria-label'] ?? (props['aria-labelledby'] ? '' : undefined)}
      aria-hidden={props['aria-hidden'] ?? (labelled ? false : true)}
      focusable={props.focusable ?? false}
    />;
  });
}

