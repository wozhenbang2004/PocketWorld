package dev.pocketengine.features.plugins.distribution;

import dev.pocketengine.core.RunControl;
import dev.pocketengine.features.plugins.PluginRules;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import org.json.JSONObject;

/** Authoring bridge to W07's actual strict codec. It neither installs nor grants anything. */
public final class SdkPackageCodec {
    private SdkPackageCodec() { }

    public static JSONObject readJson(InputStream input, RunControl control) throws Exception {
        if (input == null || control == null) throw new IllegalArgumentException("需要输入流和取消控制");
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        byte[] buffer = new byte[4096];
        while (true) {
            control.check();
            int count = input.read(buffer, 0, Math.min(buffer.length, PluginPackages.MAX_BYTES + 1 - bytes.size()));
            if (count < 0) break;
            if (count == 0) throw new IllegalArgumentException("输入流未提供数据");
            bytes.write(buffer, 0, count);
            if (bytes.size() > PluginPackages.MAX_BYTES) throw new IllegalArgumentException("JSON超过256KiB");
        }
        control.check();
        String text = StandardCharsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT)
                .onUnmappableCharacter(CodingErrorAction.REPORT).decode(ByteBuffer.wrap(bytes.toByteArray())).toString();
        return PackageJson.parse(text);
    }

    /** The generated bytes must still pass PluginPackages.inspect; do not normalize away unknown fields. */
    public static byte[] declaration(JSONObject authored, JSONObject source) throws Exception {
        JSONObject normalized = PluginRules.manifest(authored);
        return jsonBytes(new JSONObject().put("format", PluginPackages.FORMAT)
                .put("manifestSha256", PluginPackages.declarationDigest(normalized))
                .put("manifest", authored).put("source", source));
    }

    public static byte[] jsonBytes(JSONObject value) throws Exception {
        byte[] bytes = PackageJson.canonical(value).getBytes(StandardCharsets.UTF_8);
        if (bytes.length > PluginPackages.MAX_BYTES) throw new IllegalArgumentException("JSON超过256KiB");
        return bytes;
    }

    public static String digest(JSONObject value) throws Exception { return PluginPackages.hash(jsonBytes(value)); }
}
