/** Native owner selection. No model URI tool or second import store. New UI-fit implementation. */
@Composable
internal fun NativeProjectSourceImportSection(flow: ProjectPackageCoordinator) {
    val state = flow.state
    var generated by remember { mutableStateOf(false) }
    var stripSingleRoot by remember { mutableStateOf(true) }
    var details by remember { mutableStateOf(false) }
    ImportSurface(title = "从现有源码开始", subtitle = "目录或 ZIP → 核对文件 → 创建新项目") {
        SourceImportCaption("原文件不改动，代码不会自动运行。")
        ImportPrimaryAction(onClick = { flow.pickSourceDirectory(generated) }, enabled = !state.busy && state.pendingImport == null && state.pendingFreeze == null, modifier = Modifier.testTag("project_import_source_tree")) { Text("选择源码目录…") }
        OutlinedButton(onClick = { flow.pickSourceZip(generated, stripSingleRoot) }, enabled = !state.busy && state.pendingImport == null && state.pendingFreeze == null, shape = RoundedCornerShape(12.dp), modifier = Modifier.fillMaxWidth().heightIn(min = 48.dp).testTag("project_import_source_zip")) { Text("选择普通 ZIP…") }
        SourceImportCaption("默认排除生成目录、依赖缓存、Git 历史与已知凭据配置。这不是秘密扫描，导入前仍需核对清单。")
        Text(if (generated) "选项：包含生成目录" else "选项：排除生成目录", style = MaterialTheme.typography.labelMedium, color = SecondaryInk)
        ImportDisclosure("导入选项与限制", details) { details = !details }
        AnimatedVisibility(details) {
            Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                ImportCheckRow("包含生成目录", "build、dist、out 等；默认不包含", generated, !state.busy) { generated = it }
                ImportCheckRow("移除 ZIP 外包目录", "仅有一层外包目录时生效", stripSingleRoot, !state.busy) { stripSingleRoot = it }
                SourceImportCaption("最多 2000 文件、2000 目录，单文件 2MiB、纳入合计 16MiB、路径 40 层。普通 ZIP 最多 20MiB，全部条目的声明展开量最多 16MiB。不接受 ZIP64、加密、注释、链接或特殊 Unix 文件；未下载完整、虚拟文件或别名冲突会拒绝。二进制按原字节复制。")
                SourceImportCaption("读取失败不会发布半个项目。不保留来源 URI 或持久权限，也不向模型转交来源读取权。清理未完成缓存不会删除完整选择、项目或工具环境。")
                TextButton(onClick = flow::clearInterruptedSources, enabled = !state.busy, modifier = Modifier.testTag("project_import_source_clear_interrupted")) { Text("清理未完成读取缓存") }
            }
        }
        TextButton(onClick = flow::refresh, enabled = !state.busy) { Text("查看已保留的完整选择") }
    }
    HorizontalDivider(Modifier.padding(vertical = 12.dp))
}

@Composable
internal fun ProjectImportedSourceEvidence(evidence: JSONObject) {
    Text(when (evidence.optString("sourceKind")) { "saf_tree" -> "已核对的目录快照"; "git_https" -> "已核对的Git源码版本"; else -> "已核对的普通 ZIP 源码" }, style = MaterialTheme.typography.titleSmall)
    SourceImportCaption(evidence.optString("sourceLabel"))
    val stripped = evidence.optJSONObject("original")?.optString("singleRootStripped").orEmpty()
    if (stripped.isNotEmpty()) SourceImportCaption("已去掉外包目录 $stripped，下面显示新项目中的实际路径。")
    if (evidence.optString("sourceKind") == "git_https") SourceImportCaption("这份便携源码包本身不含Git历史；原Git入口会另核同版历史后发布，不通过普通ZIP恢复凭据或授权。")
    SourceImportCaption("确认后创建新项目，不继承来源权限、旧任务或运行授权。")
}

@Composable
private fun SourceImportCaption(text: String, modifier: Modifier = Modifier) { Text(text, color = SecondaryInk, style = MaterialTheme.typography.bodySmall, modifier = modifier.padding(vertical = 4.dp)) }

// Native adaptation of the retained Affect permission-request anatomy (v3 0e69029b):
// object summary, separated scope, one explicit primary decision, secondary disclosure.
// Presentation only; callers own all task state and authorization.
@Composable
internal fun ImportSurface(title: String, subtitle: String? = null, content: @Composable ColumnScope.() -> Unit) {
    Surface(modifier = Modifier.fillMaxWidth().padding(vertical = 6.dp).pocketDepth(PocketDepth.CONTENT, 16.dp),
        shape = RoundedCornerShape(16.dp), color = MaterialTheme.colorScheme.surface,
        border = BorderStroke(.5.dp, Line)) {
        Column(Modifier.padding(16.dp).animateContentSize(), verticalArrangement = Arrangement.spacedBy(10.dp)) {
            Text(title, style = MaterialTheme.typography.titleMedium, color = Ink)
            subtitle?.let { Text(it, style = MaterialTheme.typography.bodySmall, color = SecondaryInk) }
            content()
        }
    }
}

@Composable
internal fun ImportCheckRow(title: String, description: String? = null, checked: Boolean, enabled: Boolean, onCheckedChange: (Boolean) -> Unit) {
    Row(Modifier.fillMaxWidth().heightIn(min = 48.dp).toggleable(value = checked, enabled = enabled, role = Role.Checkbox, onValueChange = onCheckedChange).padding(vertical = 4.dp),
        verticalAlignment = Alignment.CenterVertically) {
        Checkbox(checked = checked, onCheckedChange = null, enabled = enabled)
        Column(Modifier.weight(1f).padding(start = 12.dp)) {
            Text(title, style = MaterialTheme.typography.bodyMedium, color = if (enabled) Ink else SecondaryInk)
            description?.let { Text(it, style = MaterialTheme.typography.bodySmall, color = SecondaryInk) }
        }
    }
}

@Composable
internal fun ImportDisclosure(label: String, expanded: Boolean, onClick: () -> Unit) {
    val rotation by animateFloatAsState(if (expanded) 180f else 0f, label = "import details disclosure")
    TextButton(onClick = onClick, modifier = Modifier.fillMaxWidth().heightIn(min = 48.dp).semantics { stateDescription = if (expanded) "已展开" else "已收起" }, contentPadding = PaddingValues(horizontal = 0.dp)) {
        Text(label, modifier = Modifier.weight(1f), textAlign = androidx.compose.ui.text.style.TextAlign.Start)
        AffectGlyph("chevron", modifier = Modifier.graphicsLayer { rotationZ = rotation }, color = SecondaryInk)
    }
}

@Composable
internal fun ImportPrimaryAction(onClick: () -> Unit, enabled: Boolean, modifier: Modifier = Modifier, content: @Composable RowScope.() -> Unit) {
    val interaction = remember { MutableInteractionSource() }
    val pressed by interaction.collectIsPressedAsState()
    val travel by animateDpAsState(if (pressed && enabled) 1.dp else 0.dp, label = "import action press")
    Button(onClick = onClick, enabled = enabled, interactionSource = interaction,
        shape = RoundedCornerShape(12.dp),
        elevation = ButtonDefaults.buttonElevation(defaultElevation = 2.dp, pressedElevation = 0.dp, disabledElevation = 0.dp),
        modifier = modifier.fillMaxWidth().heightIn(min = 48.dp).graphicsLayer { translationY = travel.toPx() }, content = content)
}

@Composable
internal fun ImportFeedback(text: String, error: Boolean = false) {
    Surface(color = Soft, shape = RoundedCornerShape(10.dp), modifier = Modifier.fillMaxWidth().semantics { liveRegion = LiveRegionMode.Polite }) {
        Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
            Text(if (error) "需要处理" else "当前结果", style = MaterialTheme.typography.labelMedium, color = Ink)
            Text(text, style = MaterialTheme.typography.bodySmall, color = SecondaryInk)
        }
    }
}
