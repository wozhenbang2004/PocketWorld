/** Native owner selection. No model URI tool or second import store. New UI-fit implementation. */
@Composable
internal fun NativeProjectSourceImportSection(flow: ProjectPackageCoordinator) {
    val state = flow.state
    var generated by remember { mutableStateOf(false) }
    var stripSingleRoot by remember { mutableStateOf(true) }
    var details by remember { mutableStateOf(false) }
    Text("从现有源码开始", fontSize = 18.sp, fontWeight = FontWeight.SemiBold)
    SourceImportCaption("选择目录或普通 ZIP，核对范围后创建新项目。原文件不改动，代码不会自动运行。")
    Row(Modifier.fillMaxWidth()) { Checkbox(generated, { generated = it }, enabled = !state.busy); SourceImportCaption("包含 build、dist、out 等生成目录", Modifier.weight(1f)) }
    Row(Modifier.fillMaxWidth()) { Checkbox(stripSingleRoot, { stripSingleRoot = it }, enabled = !state.busy); SourceImportCaption("普通 ZIP 只有一层外包目录时，去掉这一层", Modifier.weight(1f)) }
    Button(onClick = { flow.pickSourceDirectory(generated) }, enabled = !state.busy && state.pendingImport == null && state.pendingFreeze == null, modifier = Modifier.fillMaxWidth().testTag("project_import_source_tree")) { Text("选择源码目录…") }
    OutlinedButton(onClick = { flow.pickSourceZip(generated, stripSingleRoot) }, enabled = !state.busy && state.pendingImport == null && state.pendingFreeze == null, modifier = Modifier.fillMaxWidth().testTag("project_import_source_zip")) { Text("选择普通 ZIP…") }
    TextButton(onClick = flow::refresh, enabled = !state.busy) { Text("读取已保留的完整选择") }
    SourceImportCaption("依赖缓存、Git 历史及已知凭据配置会排除。请检查下方清单；这不是秘密扫描。")
    TextButton(onClick = { details = !details }) { Text(if (details) "收起详细范围" else "大小限制与未完成读取") }
    if (details) {
        SourceImportCaption("最多 2000 文件、2000 目录，单文件 2MiB、纳入合计 16MiB、路径 40 层。普通 ZIP 最多 20MiB，全部条目的声明展开量最多 16MiB。不接受 ZIP64、加密、注释、链接或特殊 Unix 文件；未下载完整、虚拟文件或别名冲突会拒绝。二进制按原字节复制。")
        SourceImportCaption("读取失败不会发布半个项目。不保留来源 URI 或持久权限，也不向模型转交来源读取权。清理未完成缓存不会删除完整选择、项目或工具环境。")
        TextButton(onClick = flow::clearInterruptedSources, enabled = !state.busy, modifier = Modifier.testTag("project_import_source_clear_interrupted")) { Text("仅清理未完成的读取缓存") }
    }
    HorizontalDivider(Modifier.padding(vertical = 12.dp))
}

@Composable
internal fun ProjectImportedSourceEvidence(evidence: JSONObject) {
    Text(if (evidence.optString("sourceKind") == "saf_tree") "已核对的目录快照" else "已核对的普通 ZIP 源码", fontSize = 15.sp, fontWeight = FontWeight.SemiBold)
    SourceImportCaption(evidence.optString("sourceLabel"))
    val stripped = evidence.optJSONObject("original")?.optString("singleRootStripped").orEmpty()
    if (stripped.isNotEmpty()) SourceImportCaption("已去掉外包目录 $stripped，下面显示新项目中的实际路径。")
    SourceImportCaption("确认后创建新项目，不继承来源权限、旧任务或运行授权。")
}

@Composable
private fun SourceImportCaption(text: String, modifier: Modifier = Modifier) { Text(text, color = SecondaryInk, fontSize = 13.sp, lineHeight = 21.sp, modifier = modifier.padding(vertical = 4.dp)) }
