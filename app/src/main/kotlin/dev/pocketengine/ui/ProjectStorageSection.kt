@OptIn(ExperimentalMaterial3Api::class)
@Composable internal fun NativeOwnerProjectStorage(flow: ProjectStorageCoordinator) {
    val state = flow.state
    TextButton(onClick = flow::open, modifier = Modifier.testTag("owner_project_storage_open")) { Text("项目存储与清理") }
    if (!state.open) return
    var pendingDiagnostic by remember(flow) { mutableStateOf<NativeDiagnosticWindow.Ticket?>(null) }
    val diagnosticPicker = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/json")) { uri ->
        val original = pendingDiagnostic; pendingDiagnostic = null; flow.diagnosticExportResult(original, uri)
    }
    var showProtected by remember { mutableStateOf(false) }
    var confirmed by remember(state.review?.optString("actionId")) { mutableStateOf(false) }
    var details by remember { mutableStateOf(false) }
    val policy = state.inventory?.optJSONObject("retentionPolicy")
    var generations by remember(policy?.optString("revision")) { mutableStateOf(policy?.optInt("keepOldRuntimeGenerations", 2) ?: 2) }
    var backups by remember(policy?.optString("revision")) { mutableStateOf(policy?.optInt("keepRecentBackupCopies", 2) ?: 2) }
    var generated by remember(policy?.optString("revision")) { mutableStateOf(policy?.optBoolean("suggestGeneratedCleanup") == true) }
    var original by remember { mutableStateOf(state.originalAction.orEmpty()) }
    LaunchedEffect(state.open, state.busy, state.originalAction, state.original?.optString("status")) {
        if (!state.busy && state.originalAction != null && state.original?.optString("status") in setOf("queued", "running")) { delay(700); flow.poll() }
    }
    ModalBottomSheet(onDismissRequest = flow::closePage, sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)) {
        Column(Modifier.fillMaxWidth().fillMaxHeight(.93f).padding(horizontal = 22.dp).navigationBarsPadding()) {
            Text("项目存储", fontSize = 22.sp, fontWeight = FontWeight.SemiBold)
            StorageCaption(state.inventory?.let { "文件系统当前可用 ${size(it.optLong("filesystemUsableBytes"))}。清理前请核对，原项目、固定成果与用户 HOME 默认保留。" } ?: "读取实际目录占用，不把读取失败当成0字节。")
            LazyColumn(Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(10.dp)) {
                item { NativeStorageDiagnosticMetadata(flow) {
                    flow.prepareDiagnosticExport()?.let { ticket ->
                        pendingDiagnostic = ticket
                        try { diagnosticPicker.launch("pocketworld-diagnostic-metadata.json") }
                        catch (unavailable: Exception) { pendingDiagnostic = null; flow.diagnosticPickerUnavailable(ticket) }
                    }
                } }
                item {
                    TextButton(onClick = flow::refresh, enabled = !state.busy) { Text(if (state.busy) "读取中…" else "重新计量") }
                    Row { Checkbox(showProtected, { showProtected = it }); Text("显示受保护或空的范围", Modifier.weight(1f).padding(top = 13.dp), fontSize = 13.sp) }
                    Row { TextButton(onClick = flow::suggest, enabled = !state.busy && state.review == null) { Text("按保留规则建议勾选") }; TextButton(onClick = { details = !details }) { Text(if (details) "收起说明" else "保留规则与计量说明") } }
                    if (details) {
                        StorageCaption("逻辑字节不等于实际磁盘块，也不等于独占回收量；硬链接、打开的文件和文件系统回收时机都会影响可用空间。项目根目录、HOME 与其下级依赖/生成/内容缓存有重叠，不把分组相加。链接不跟随，读取失败或条目超限显示未知，不依据截断清单删除。")
                        StorageCaption("清理须停止原执行、取得退出与释放证据。原运行环境维护租约会拒绝新准备/执行进入；同UID程序不是OS沙箱。未知的原进程、已变化的目录、当前rootfs、用户HOME、原回执和固定成果不会被当缓存泛删。")
                        Text("建议保留旧环境：$generations 版", fontSize = 13.sp)
                        Row { TextButton(onClick = { generations = (generations - 1).coerceAtLeast(0) }) { Text("−") }; TextButton(onClick = { generations = (generations + 1).coerceAtMost(5) }) { Text("＋") } }
                        Text("建议保留本机备份：$backups 份", fontSize = 13.sp)
                        Row { TextButton(onClick = { backups = (backups - 1).coerceAtLeast(0) }) { Text("−") }; TextButton(onClick = { backups = (backups + 1).coerceAtMost(5) }) { Text("＋") } }
                        Row { Checkbox(generated, { generated = it }); Text("把未固定生成目录列入清理建议（可能丢失未保存输出）", Modifier.weight(1f).padding(top = 13.dp), fontSize = 13.sp) }
                        TextButton(onClick = { flow.savePolicy(generations, backups, generated) }, enabled = !state.busy) { Text("保存建议规则，不启用自动删除") }
                    }
                }
                val rows = state.inventory?.optJSONArray("groups")?.rows().orEmpty().filter { showProtected || it.optBoolean("cleanable") && (it.optJSONObject("usage")?.optLong("logicalBytes", -1) ?: -1) != 0L || it.optJSONObject("usage")?.optBoolean("complete") != true }
                items(rows, key = { it.getString("id") }) { row ->
                    val id = row.getString("id"); val usage = row.optJSONObject("usage"); val cleanable = row.optBoolean("cleanable") && usage?.optBoolean("complete") == true
                    Row(Modifier.fillMaxWidth()) {
                        if (cleanable) Checkbox(id in state.selected, { flow.select(id, it) }, enabled = !state.busy && state.review == null)
                        Column(Modifier.weight(1f).padding(top = if (cleanable) 10.dp else 0.dp)) {
                            Text(row.optString("label"), fontSize = 14.sp, fontWeight = FontWeight.Medium)
                            StorageCaption(if (usage?.optBoolean("complete") == true) "${size(usage.optLong("logicalBytes"))} · ${usage.optInt("files")} 个文件${if (cleanable) "" else " · 保留"}" else "未能完整读取 · 不可据此清理")
                            StorageCaption(row.optString("note"))
                        }
                    }
                    HorizontalDivider()
                }
                if (state.caches.size > backups) item {
                    Text("超过建议保留数的本机备份", fontSize = 15.sp, fontWeight = FontWeight.SemiBold)
                    StorageCaption("这里只给建议，不删除。逐份核对固定字节后，从原备份页明确移除本机缓存；未决恢复依赖的副本会拒绝删除。")
                    state.caches.drop(backups).forEach { cache -> TextButton(onClick = { flow.backupCache(cache.getString("selectionId")) }, enabled = !state.busy) { Text("核对本机备份 · ${size(cache.optLong("archiveBytes"))}") } }
                }
                state.review?.let { review -> item {
                    Text("确认清理 ${review.optJSONArray("targets")?.length() ?: 0} 个固定范围", fontSize = 16.sp, fontWeight = FontWeight.SemiBold)
                    StorageCaption("不会删除原项目源文件、已固定成果或整个用户 HOME。依赖可能需重新安装；未保存的生成目录会丢失。目录漂移即停止，跨目录不是原子事务，已删除缓存不会回滚。")
                    review.optJSONArray("targets")?.rows()?.forEach { target ->
                        val description = state.inventory?.optJSONArray("groups")?.rows()?.firstOrNull { it.optString("id") == target.optString("id") }
                        StorageCaption((description?.optString("label") ?: target.optString("id")) + " · " + size(target.optLong("logicalBytes")))
                    }
                    Row { Checkbox(confirmed, { confirmed = it }); Text("我已核对所选范围，并接受这些缓存或未固定输出被移除", Modifier.weight(1f).padding(top = 13.dp), fontSize = 13.sp) }
                    Button(onClick = flow::confirm, enabled = confirmed && !state.busy, modifier = Modifier.fillMaxWidth().testTag("owner_project_storage_confirm")) { Text("仅清理这些范围") }
                    TextButton(onClick = flow::cancelReview) { Text("保留，不清理") }
                } }
                if (state.originalAction != null) item {
                    Text("原清理动作", fontWeight = FontWeight.SemiBold, fontSize = 15.sp)
                    StorageCaption(when (state.original?.optString("status")) { "running", "queued" -> "原任务正在清理。"; "completed" -> "原清理已取得回执；之后重新生成的缓存不会自动再删。"; else -> "原结果待核，不能自动重放删除。" })
                    TextButton(onClick = flow::query, enabled = !state.busy) { Text("只读核对原范围") }
                    if (state.original?.optString("status") in setOf("running", "queued", "stopping")) TextButton(onClick = flow::stop, enabled = !state.busy) { Text("请求停止后续删除") }
                    if (details) StorageCaption(state.originalAction)
                }
                item {
                    if (details) { OutlinedTextField(original, { if (it.length <= 36) original = it }, label = { Text("原清理任务编号") }, singleLine = true, modifier = Modifier.fillMaxWidth()); TextButton(onClick = { flow.readOriginal(original) }, enabled = !state.busy && original.matches(Regex("[a-f0-9-]{36}"))) { Text("读取原动作，不执行") } }
                    state.notice?.let { StorageCaption(it) }; state.error?.let { Text(it, color = MaterialTheme.colorScheme.error, fontSize = 13.sp) }
                }
            }
            if (state.review == null) Button(onClick = flow::reviewSelected, enabled = !state.busy && state.selected.isNotEmpty(), modifier = Modifier.fillMaxWidth().testTag("owner_project_storage_review")) { Text("审阅所选 ${state.selected.size} 个范围") }
            TextButton(onClick = flow::closePage, modifier = Modifier.fillMaxWidth()) { Text("完成，返回") }
        }
    }
}
@Composable private fun NativeStorageDiagnosticMetadata(flow: ProjectStorageCoordinator, export: () -> Unit) {
    val state = flow.state
    var expanded by remember(state.diagnosticSha) { mutableStateOf(false) }
    TextButton(onClick = flow::readDiagnostics, enabled = !state.busy && state.review == null && !state.diagnosticPickerPending, modifier = Modifier.testTag("owner_diagnostic_collect")) { Text("读取本机脱敏诊断元数据") }
    StorageCaption("只读取固定状态、逻辑计数和身份指纹；各域独立限时。不会读取记忆或任务正文、截图、日志内容、地址或凭据，不运行修复/自检，不改变任务。后台手机会话在此入口未采样。")
    if (state.diagnosticText != null) {
        TextButton(onClick = { expanded = !expanded }) { Text(if (expanded) "收起将保存的元数据" else "查看将保存的全部元数据") }
        if (expanded) {
            Text(state.diagnosticText, fontSize = 11.sp, lineHeight = 17.sp)
            StorageCaption("固定字节：${state.diagnosticBytes} · SHA-256 ${state.diagnosticSha}")
            Row { Checkbox(state.diagnosticReviewed, flow::reviewDiagnostics, enabled = !state.busy && !state.diagnosticPickerPending && !state.diagnosticExportEntered); Text("我已核对这个固定快照，明确保存这些元数据", Modifier.weight(1f).padding(top = 13.dp), fontSize = 13.sp) }
            OutlinedButton(onClick = export, enabled = state.diagnosticReviewed && !state.busy && !state.diagnosticPickerPending && !state.diagnosticExportEntered, modifier = Modifier.testTag("owner_diagnostic_export")) { Text("选择位置，保存这些字节") }
            StorageCaption("仅在系统文件选择器授予的位置写入。云端文档提供方可能自行同步；本App不会自动发送诊断。取消或关闭页面后旧选择不能再次写入，失败目标可能不完整。")
        }
    }
    HorizontalDivider()
}
@Composable private fun StorageCaption(text: String) { Text(text, fontSize = 12.sp, lineHeight = 19.sp, color = SecondaryInk) }
private fun size(bytes: Long): String = when { bytes >= 1024L * 1024 * 1024 -> "%.2f GiB".format(java.util.Locale.ROOT, bytes / (1024.0 * 1024 * 1024)); bytes >= 1024 * 1024 -> "%.1f MiB".format(java.util.Locale.ROOT, bytes / (1024.0 * 1024)); bytes >= 1024 -> "%.1f KiB".format(java.util.Locale.ROOT, bytes / 1024.0); else -> "$bytes B" }
private fun JSONArray.rows(): List<JSONObject> = (0 until length()).mapNotNull { optJSONObject(it) }
