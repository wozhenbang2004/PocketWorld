/** Scope follows the project page, not a LazyColumn item's visibility or a preview WebView. */
@Composable
internal fun ProjectPackageOwnerScope(checkout: JSONObject?, projectId: String?, controller: PocketWorldController) {
    val flow = controller.projectPackages
    LaunchedEffect(projectId, checkout?.optString("id")) { flow.activate(projectId, checkout) }
    DisposableEffect(flow) { onDispose { flow.deactivate() } }
    if (flow.state.ownerPanelRequested) Dialog(onDismissRequest = flow::closeOwnerPanel, properties = DialogProperties(usePlatformDefaultWidth = false, decorFitsSystemWindows = false)) {
        Surface(Modifier.fillMaxSize(), color = MaterialTheme.colorScheme.surface) {
            Column(Modifier.fillMaxSize().systemBarsPadding().imePadding().padding(horizontal = 16.dp)) {
                TextButton(onClick = flow::closeOwnerPanel) { Text("返回原任务与项目") }
                Column(Modifier.weight(1f).verticalScroll(rememberScrollState())) { NativeProjectPackageWorkbench(checkout, projectId, controller, true) }
            }
        }
    }
}

/** Actual files and immutable project packages, distinct from the older text-only version export. */
@Composable
internal fun NativeProjectPackageWorkbench(checkout: JSONObject?, projectId: String?, controller: PocketWorldController, ownerPanel: Boolean = false) {
    val flow = controller.projectPackages
    val current = flow.state
    var removing by remember { mutableStateOf<JSONObject?>(null) }
    var expanded by remember { mutableStateOf(false) }
    var mode by remember(checkout?.optString("id")) { mutableStateOf("source_project") }
    var entry by remember(checkout?.optString("id")) { mutableStateOf("dist/index.html") }
    var generated by remember(checkout?.optString("id")) { mutableStateOf(false) }
    var confirmed by remember(current.selection?.optString("manifestIdentity")) { mutableStateOf(false) }
    var importName by remember(current.staged?.optString("selectionId")) { mutableStateOf(current.staged?.optJSONObject("manifest")?.optJSONObject("project")?.optString("name").orEmpty()) }
    var sameProject by remember(current.staged?.optString("selectionId"), checkout?.optString("id")) { mutableStateOf(false) }
    var importConfirmed by remember(current.importPlan?.optJSONObject("plan")?.optString("planDigest")) { mutableStateOf(false) }
    var previewEntry by remember(current.artifact?.optString("id")) { mutableStateOf(current.artifact?.optString("entryPath")?.takeIf { it.isNotEmpty() } ?: current.artifact?.optJSONObject("manifest")?.optJSONArray("files")?.objects()?.firstOrNull { it.optString("mimeType") == "text/html" }?.optString("path").orEmpty()) }
    TextButton(onClick = { expanded = !expanded; if (expanded) flow.refresh() }, modifier = Modifier.testTag("project_package_entry")) { Text(if (expanded) "收起项目包与固定成果" else "项目包、固定成果与重新导入") }
    if (!expanded && !ownerPanel) return
    if (current.projectId != projectId || current.checkoutId != checkout?.optString("id")) { PackageCaption("正在核对原项目包入口，未打开其他项目的成果。"); return }
    Text("带走实际项目，再从固定版本继续", fontSize = 17.sp, fontWeight = FontWeight.SemiBold)
    PackageCaption("完整项目包读取当前实际文件，包含支持的二进制；旧版「导出项目」只导文字版本库。这里只保存、查看或明确导入，不会安装依赖、启动服务、恢复任务或运行授权。")
    if (current.busy) { LinearProgressIndicator(Modifier.fillMaxWidth()); TextButton(onClick = flow::cancel) { Text("停止等待，保留原动作定位") } }
    current.error?.let { Text(it, color = Danger, fontSize = 13.sp, lineHeight = 21.sp) }
    current.notice?.let { PackageCaption(it) }
    current.pendingFreeze?.let { pin ->
        PackageCaption("原保存动作 ${pin.optString("clientSnapshotId").take(8)} 仍待核对，不会重复保存。")
        TextButton(onClick = flow::queryFreeze, enabled = !current.busy) { Text("只查询原保存结果") }
        if (current.retryFreeze) OutlinedButton(onClick = flow::retryFreeze, enabled = !current.busy) { Text("明确重试这个原保存动作") }
    }
    current.pendingImport?.let { pin ->
        PackageCaption("原导入动作 ${pin.optString("clientImportId").take(8)} 仍待核对，不会自动另建项目。")
        TextButton(onClick = flow::queryImport, enabled = !current.busy) { Text("只查询原导入结果") }
        if (current.retryImport) OutlinedButton(onClick = flow::retryImport, enabled = !current.busy) { Text("明确重试这个原导入方案") }
    }
    if (current.sourceImportRequested) NativeProjectSourceImportSection(flow)
    if (!current.sourceImportRequested && !current.reviewingTaskDelivery && checkout != null && current.pendingFreeze == null) {
        Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            FilterChip(mode == "source_project", { mode = "source_project"; confirmed = false; flow.forgetSelection() }, enabled = !current.busy, label = { Text("源项目包") })
            FilterChip(mode == "web_output", { mode = "web_output"; confirmed = false; flow.forgetSelection() }, enabled = !current.busy, label = { Text("固定网页成果") })
        }
        if (mode == "web_output") OutlinedTextField(entry, { entry = it; confirmed = false; flow.forgetSelection() }, enabled = !current.busy, label = { Text("当前实际HTML入口") }, singleLine = true, modifier = Modifier.fillMaxWidth())
        else {
            Row { Checkbox(generated, { generated = it; confirmed = false; flow.forgetSelection() }, enabled = !current.busy); PackageCaption("同时包含根目录 build/dist/out/target/coverage 中的实际文件") }
        }
        PackageCaption("始终排除依赖、venv、Git私有历史、已知凭据与账号配置。排除清单可逐页查看；它不是任意源码中的秘密扫描，请在导出前自行核对。采集前后会核对所选文件，不能证明活动进程没有在中途改写。")
        OutlinedButton(onClick = { confirmed = false; flow.review(mode, entry.trim(), generated) }, enabled = !current.busy, modifier = Modifier.testTag("project_package_review")) { Text("读取实际包含范围") }
    }
    current.selection?.let { selected ->
        Text("待保存的实际范围", fontSize = 15.sp, fontWeight = FontWeight.SemiBold)
        ProjectPackageManifest(selected.getJSONObject("manifest"), selected.getString("manifestIdentity"))
        if (current.reviewingTaskDelivery) PackageCaption("只读原任务的待批准完整清单。请返回原任务决定批准或拒绝，不会在这里另建保存动作。")
        else {
            Row { Checkbox(confirmed, { confirmed = it }); PackageCaption("我已核对包含与排除项，确认将这些当前字节保存为固定成果。它不证明构建成功或输出最新。") }
            Button(onClick = { confirmed = false; flow.freeze() }, enabled = confirmed && !current.busy && current.pendingFreeze == null, modifier = Modifier.testTag("project_package_freeze")) { Text("保存此固定文件版本") }
        }
    }
    HorizontalDivider(Modifier.padding(vertical = 12.dp), color = Line)
    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        TextButton(onClick = flow::refresh, enabled = !current.busy) { Text("读取已保存成果") }
        TextButton(onClick = flow::pickImport, enabled = !current.busy && current.pendingImport == null, modifier = Modifier.testTag("project_package_import_picker")) { Text("从系统文件导入项目包") }
    }
    if (current.artifacts.isEmpty()) PackageCaption("还没有固定项目包。普通文件版本与开发中的实际文件都未被删除。")
    current.artifacts.asReversed().forEach { item ->
        TextButton(onClick = { flow.open(item) }, enabled = !current.busy && item.optString("availability") != "retired", modifier = Modifier.fillMaxWidth()) {
            Column(Modifier.fillMaxWidth()) {
                Text("${item.optString("name")} · 固定版本 ${item.optInt("versionSequence")}")
                Text("${item.optInt("fileCount")} 文件 · ${item.optLong("sizeBytes")} 字节 · ${item.optString("sha256").take(12)}", fontSize = 11.sp, color = SecondaryInk)
            }
        }
        if (item.optString("availability") == "retired") TextButton(onClick = { removing = item }, enabled = !current.busy) { Text("已撤下 · 核对并重试这个版本的文件清理") }
    }
    current.artifact?.let { item ->
        Text("原固定版本 ${item.optInt("versionSequence")} · ${item.optString("id").take(8)}", fontWeight = FontWeight.SemiBold, fontSize = 15.sp)
        PackageCaption("来自原副本 ${item.optString("checkoutId").take(8)}；原字节摘要 ${item.optString("sha256").take(16)}。当前项目修改不会替换它，重新打开也不会回退到当前文件。")
        item.optJSONObject("manifest")?.let { manifest ->
            ProjectPackageManifest(manifest, item.optString("manifestIdentity"))
            val html = manifest.getJSONArray("files").objects().filter { it.optString("mimeType") == "text/html" }.map { it.getString("path") }
            if (html.isNotEmpty()) {
                OutlinedTextField(previewEntry, { previewEntry = it }, label = { Text("这份固定成果中的HTML入口") }, singleLine = true, modifier = Modifier.fillMaxWidth())
                TextButton(onClick = { flow.preview(previewEntry.trim()) }, enabled = !current.busy) { Text("打开原HTML与实际资源") }
            } else PackageCaption("此包没有HTML入口；二进制原字节仍会完整导出与导入，但不冒充已可视预览。")
        }
        OutlinedButton(onClick = flow::offerExport, enabled = !current.busy, modifier = Modifier.testTag("project_package_export")) { Text("导出这个原项目包…") }
        TextButton(onClick = { removing = item }, enabled = !current.busy) { Text("移除这个固定版本…") }
    }
    current.preview?.let { frozen -> key(frozen.identity) {
        val context = LocalContext.current
        var view by remember { mutableStateOf<ProjectBundleWebView?>(null) }
        var error by remember { mutableStateOf<String?>(null) }
        val lifecycle = remember(context) { generateSequence(context) { (it as? ContextWrapper)?.baseContext?.takeUnless { base -> base === it } }.filterIsInstance<LifecycleOwner>().firstOrNull()?.lifecycle }
        DisposableEffect(lifecycle) {
            val observer = LifecycleEventObserver { _, event -> if (event == Lifecycle.Event.ON_STOP) { view?.release(); view = null; flow.closePreview() } }
            lifecycle?.addObserver(observer)
            onDispose { lifecycle?.removeObserver(observer); view?.release(); view = null }
        }
        PackageCaption("固定成果 ${frozen.artifactId?.take(8)} 的独立预览。只读取已归档HTML/CSS/JS/图片等资源，无外网、文件选择器或Native权限桥；不是服务就绪证明。")
        AndroidView(factory = { ctx -> ProjectBundleWebView(ctx, frozen, object : ProjectBundleWebView.Events {
            override fun error(message: String) { error = message }
            override fun console(level: String, text: String, source: String, line: Int) { if (level in setOf("ERROR", "WARNING")) error = "$level: ${text.take(500)}" }
        }).also { view = it } }, modifier = Modifier.fillMaxWidth().height(420.dp))
        error?.let { Text(it, color = Danger, fontSize = 13.sp) }
        TextButton(onClick = flow::closePreview) { Text("关闭固定预览，返回原项目") }
    } }
    if (current.stagedPackages.isNotEmpty()) {
        Text("待处理的导入临时包", fontWeight = FontWeight.SemiBold, fontSize = 15.sp, modifier = Modifier.padding(top = 16.dp))
        current.stagedPackages.forEach { item -> TextButton(onClick = { flow.selectStaged(item) }, enabled = !current.busy && current.pendingImport == null) { Text(item.optJSONObject("manifest")?.optJSONObject("project")?.optString("name")?.takeIf { it.isNotBlank() } ?: "临时包 ${item.optString("selectionId").take(8)} · ${if (item.optBoolean("available")) "可核对" else "校验失败"}") } }
    }
    current.staged?.let { item ->
        item.optJSONObject("manifest")?.let { manifest ->
            item.optJSONObject("sourceEvidence")?.let { ProjectImportedSourceEvidence(it) }
            ProjectPackageManifest(manifest, item.getString("manifestIdentity"))
            OutlinedTextField(importName, { importName = it.take(80); importConfirmed = false; flow.forgetImportPlan() }, enabled = !current.busy && current.pendingImport == null, label = { Text("导入后的项目/副本名称") }, singleLine = true, modifier = Modifier.fillMaxWidth())
            Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                FilterChip(!sameProject, { sameProject = false; importConfirmed = false; flow.forgetImportPlan() }, enabled = !current.busy && current.pendingImport == null, label = { Text("新项目") })
                if (checkout != null && !item.has("sourceEvidence")) FilterChip(sameProject, { sameProject = true; importConfirmed = false; flow.forgetImportPlan() }, enabled = !current.busy && current.pendingImport == null, label = { Text("原项目的新副本") })
            }
            TextButton(onClick = { importConfirmed = false; flow.planImport(importName.trim(), sameProject && !item.has("sourceEvidence")) }, enabled = importName.isNotBlank() && !current.busy && current.pendingImport == null) { Text("核对明确导入方案") }
        }
        TextButton(onClick = flow::discardStage, enabled = !current.busy && current.pendingImport == null) { Text("仅移除此导入临时包") }
    }
    current.importPlan?.let { reviewed ->
        PackageCaption(reviewed.getString("message"))
        PackageCaption(if (reviewed.getJSONObject("plan").getString("mode") == "new_project") "将新建项目，不复用原任务身份或运行授权。" else "原项目下会创建新的实际副本；旧目录、旧任务和旧草稿仍绑定旧副本。目标源码变化则拒绝。")
        Row { Checkbox(importConfirmed, { importConfirmed = it }); PackageCaption("我确认按此方案导入，保留旧目录；未要求安装或执行。") }
        Button(onClick = { importConfirmed = false; flow.confirmImport() }, enabled = importConfirmed && !current.busy && current.pendingImport == null, modifier = Modifier.testTag("project_package_import_confirm")) { Text("明确导入到新副本") }
    }
    removing?.let { selected -> AlertDialog(onDismissRequest = { removing = null }, title = { Text("移除这个固定版本？") }, text = { Text("仅移除固定包 ${selected.optString("id").take(8)} 与清单，不删除实际项目文件、原任务或工具环境。若要保留，请先导出；不会用最新版本替代它。") }, confirmButton = { TextButton(onClick = { removing = null; flow.removeArtifact(selected) }) { Text("明确移除此版本") } }, dismissButton = { TextButton(onClick = { removing = null }) { Text("保留") } }) }
    current.imported?.let { item ->
        PackageCaption("已发布实际副本 ${item.optString("id").take(8)}。支持的二进制按原字节保留；旧任务未改绑。在新副本重新核对环境和依赖后才能运行。")
        OutlinedButton(onClick = flow::continueImported, enabled = !current.busy, modifier = Modifier.testTag("project_package_continue_import")) { Text("打开这个新副本，继续修改") }
    }
}

@Composable
private fun ProjectPackageManifest(manifest: JSONObject, identity: String) {
    var page by remember(identity) { mutableStateOf(0) }
    var omissions by remember(identity) { mutableStateOf(false) }
    val files = manifest.getJSONArray("files").objects()
    val omitted = manifest.getJSONArray("omitted").objects()
    val rows = if (omissions) omitted else files
    val pages = maxOf(1, (rows.size + 19) / 20)
    PackageCaption("${files.size} 实际文件 · ${manifest.getLong("bytes")} 字节 · ${manifest.getJSONArray("directories").length()} 目录 · 排除 ${omitted.size} 项 · 清单 ${identity.take(12)}")
    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        TextButton(onClick = { omissions = false; page = 0 }) { Text("包含文件") }
        TextButton(onClick = { omissions = true; page = 0 }) { Text("查看排除项") }
    }
    SelectionContainer { Column { rows.drop(page * 20).take(20).forEach { row ->
        Text(row.getString("path"), fontFamily = FontFamily.Monospace, fontSize = 12.sp, modifier = Modifier.padding(top = 6.dp))
        Text(if (omissions) row.getString("reason") else "${row.getString("kind")} · ${row.getLong("bytes")} 字节 · ${row.getString("sha256").take(12)}", fontSize = 11.sp, color = SecondaryInk)
    } } }
    if (rows.isEmpty()) PackageCaption(if (omissions) "此范围没有额外排除项。" else "没有文件。")
    if (pages > 1) Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        TextButton(onClick = { page-- }, enabled = page > 0) { Text("上一页") }; PackageCaption("${page + 1}/$pages")
        TextButton(onClick = { page++ }, enabled = page + 1 < pages) { Text("下一页") }
    }
}

@Composable private fun PackageCaption(text: String) { Text(text, color = SecondaryInk, fontSize = 13.sp, lineHeight = 21.sp, modifier = Modifier.padding(vertical = 5.dp)) }
