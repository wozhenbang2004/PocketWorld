    @Test public void originalIoFailureIsPropagatedWithoutRetryOrPayloadReconstruction() throws Exception {
        IOException network = new IOException("fixture_transport_failure");
        final int[] attempts = {0};
        InputStream input = new InputStream() {
            @Override public int read() throws IOException { attempts[0]++; throw network; }
        };
        BedrockEventStream stream = new BedrockEventStream(input);
        assertSame(network, assertThrows(IOException.class, stream::nextPayload));
        assertSame(network, assertThrows(IOException.class, stream::nextPayload));
        assertEquals(1, attempts[0]);
    }

    @Test public void zeroLengthReadMakesBoundedProgressAndDecoderDoesNotOwnClose() throws Exception {
        byte[] payload = "{}".getBytes(StandardCharsets.UTF_8);
        final int[] zeroes = {0}, closes = {0};
        InputStream input = new FilterInputStream(new ByteArrayInputStream(chunk(payload))) {
            @Override public int read(byte[] bytes, int offset, int length) throws IOException {
                if (zeroes[0]++ == 0) return 0;
                return super.read(bytes, offset, length);
            }
            @Override public void close() throws IOException { closes[0]++; super.close(); }
        };
        BedrockEventStream stream = new BedrockEventStream(input);
        assertArrayEquals(payload, stream.nextPayload());
        assertNull(stream.nextPayload());
        assertEquals(0, closes[0]);
    }

    @Test public void streamFrameCountAndRawBytesHaveApplicationBounds() throws Exception {
        byte[] tiny = chunk("{}".getBytes(StandardCharsets.UTF_8));
        ByteArrayOutputStream many = new ByteArrayOutputStream();
        for (int i = 0; i < 8193; i++) many.write(tiny);
        BedrockEventStream count = new BedrockEventStream(new ByteArrayInputStream(many.toByteArray()));
        for (int i = 0; i < 8192; i++) assertNotNull(count.nextPayload());
        assertEquals("bedrock_frame_count_limit", failure(count).code);

        byte[] largePayload = ("{\"text\":\"" + "x".repeat(220_000) + "\"}").getBytes(StandardCharsets.UTF_8);
        byte[] large = chunk(largePayload);
        ByteArrayOutputStream longStream = new ByteArrayOutputStream();
        for (int i = 0; i < 16; i++) longStream.write(large);
        BedrockEventStream raw = new BedrockEventStream(new ByteArrayInputStream(longStream.toByteArray()));
        int returned = 0;
        while (true) {
            try { assertNotNull(raw.nextPayload()); returned++; }
            catch (BedrockEventStream.Failure limit) {
                assertEquals(BedrockEventStream.Kind.PROTOCOL, limit.kind);
                assertEquals("bedrock_stream_application_limit", limit.code);
                break;
            }
            assertTrue("Raw response was not bounded", returned < 16);
        }
        assertTrue(returned > 0);
    }

    private static BedrockEventStream.Failure failure(BedrockEventStream stream) {
        return assertThrows(BedrockEventStream.Failure.class, stream::nextPayload);
    }

    private static void assertProtocol(byte[] bytes) {
        assertEquals(BedrockEventStream.Kind.PROTOCOL,
            failure(new BedrockEventStream(new ByteArrayInputStream(bytes))).kind);
    }

    private static Map<String, HeaderValue> eventHeaders() {
        Map<String, HeaderValue> headers = new LinkedHashMap<>();
        headers.put(":message-type", HeaderValue.fromString("event"));
        headers.put(":event-type", HeaderValue.fromString("chunk"));
        headers.put(":content-type", HeaderValue.fromString("application/json"));
        return headers;
    }

    private static byte[] envelope(byte[] payload) throws Exception {
        return new JSONObject().put("bytes", Base64.getEncoder().encodeToString(payload)).toString().getBytes(StandardCharsets.UTF_8);
    }

    private static byte[] chunk(byte[] payload) throws Exception {
        return wire(Message.encodeHeaders(eventHeaders().entrySet()), envelope(payload));
    }

    private static byte[] wire(byte[] headers, byte[] payload) throws Exception {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        DataOutputStream out = new DataOutputStream(bytes);
        out.write(prelude(16L + headers.length + payload.length, headers.length));
        out.write(headers);
        out.write(payload);
        CRC32 crc = new CRC32(); byte[] withoutCrc = bytes.toByteArray();
        crc.update(withoutCrc, 0, withoutCrc.length);
        out.writeInt((int) crc.getValue());
        return bytes.toByteArray();
    }

    private static byte[] prelude(long total, long headers) throws Exception {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        DataOutputStream out = new DataOutputStream(bytes);
        out.writeInt((int) total); out.writeInt((int) headers);
        CRC32 crc = new CRC32(); byte[] beforeCrc = bytes.toByteArray();
        crc.update(beforeCrc, 0, beforeCrc.length); out.writeInt((int) crc.getValue());
        return bytes.toByteArray();
    }

    private static InputStream fragmented(byte[] bytes, int maxRead) {
        return new ByteArrayInputStream(bytes) {
            @Override public synchronized int read(byte[] output, int offset, int length) {
                return super.read(output, offset, Math.min(maxRead, length));
            }
        };
    }

    private static byte[] join(byte[] first, byte[] second) throws Exception {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        bytes.write(first); bytes.write(second); return bytes.toByteArray();
    }

    private static byte[] unhex(String value) {
        byte[] bytes = new byte[value.length() / 2];
        for (int i = 0; i < bytes.length; i++) bytes[i] = (byte) Integer.parseInt(value.substring(i * 2, i * 2 + 2), 16);
        return bytes;
    }
